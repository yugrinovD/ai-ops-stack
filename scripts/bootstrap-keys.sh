#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."

if ! command -v jq >/dev/null 2>&1; then
  echo "jq is required" >&2
  exit 1
fi
if [[ ! -f .env ]]; then
  echo ".env is missing; run 'make init-env'" >&2
  exit 1
fi
mkdir -p .secrets
chmod 700 .secrets
[[ -f .secrets/runtime.env ]] || { : > .secrets/runtime.env; chmod 600 .secrets/runtime.env; }

set -a
# shellcheck disable=SC1091
source ./.env
if [[ -f .secrets/runtime.env ]]; then
  # shellcheck disable=SC1091
  source ./.secrets/runtime.env
fi
set +a

ADMIN="http://127.0.0.1:${GOGATE_ADMIN_PORT:-9090}/admin/v1"
PUBLIC="http://127.0.0.1:${GOGATE_HTTP_PORT:-8080}"
AUTH="Authorization: Bearer ${GOGATE_ADMIN_TOKEN:?GOGATE_ADMIN_TOKEN is required}"
JSON="Content-Type: application/json"

echo "==> waiting for gogate at ${PUBLIC}/readyz"
for _ in $(seq 1 90); do
  if curl -fsS "${PUBLIC}/readyz" >/dev/null 2>&1; then
    break
  fi
  sleep 2
done
curl -fsS "${PUBLIC}/readyz" >/dev/null

ensure_tenant() {
  local name="$1"
  curl -fsS -X POST "${ADMIN}/tenants" -H "${AUTH}" -H "${JSON}" \
    -d "{\"name\":\"${name}\"}" | jq -r '.id'
}

key_valid() {
  local key="$1"
  [[ -n "${key}" ]] || return 1
  curl -fsS "${PUBLIC}/v1/models" -H "Authorization: Bearer ${key}" >/dev/null 2>&1
}

create_key() {
  local tenant_id="$1"
  local name="$2"
  curl -fsS -X POST "${ADMIN}/keys" -H "${AUTH}" -H "${JSON}" \
    -d "{\"tenant_id\":\"${tenant_id}\",\"name\":\"${name}\"}" | jq -r '.key'
}

upsert_quota() {
  local tenant_id="$1"
  local rpm="$2"
  local tpm="$3"
  local daily_requests="$4"
  local daily_tokens="$5"
  curl -fsS -X POST "${ADMIN}/quotas" -H "${AUTH}" -H "${JSON}" \
    -d "{\"tenant_id\":\"${tenant_id}\",\"rpm\":${rpm},\"tpm\":${tpm},\"daily_requests\":${daily_requests},\"daily_tokens\":${daily_tokens}}" >/dev/null
}

LMLOG_TENANT_ID="$(ensure_tenant lmlog)"
OPS_TENANT_ID="$(ensure_tenant ops-console)"

lmlog_key="${GOGATE_API_KEY:-}"
ops_key="${GOGATE_PLAYGROUND_API_KEY:-}"

if ! key_valid "${lmlog_key}"; then
  echo "==> creating a new lmlog gateway key"
  lmlog_key="$(create_key "${LMLOG_TENANT_ID}" lmlog)"
else
  echo "==> reusing the existing lmlog gateway key"
fi

if ! key_valid "${ops_key}"; then
  echo "==> creating a new ops-console playground key"
  ops_key="$(create_key "${OPS_TENANT_ID}" ops-console-playground)"
else
  echo "==> reusing the existing ops-console playground key"
fi

upsert_quota "${LMLOG_TENANT_ID}" \
  "${LMLOG_GATEWAY_RPM:-60}" \
  "${LMLOG_GATEWAY_TPM:-200000}" \
  "${LMLOG_GATEWAY_DAILY_REQUESTS:-20000}" \
  "${LMLOG_GATEWAY_DAILY_TOKENS:-20000000}"
upsert_quota "${OPS_TENANT_ID}" \
  "${OPS_GATEWAY_RPM:-120}" \
  "${OPS_GATEWAY_TPM:-400000}" \
  "${OPS_GATEWAY_DAILY_REQUESTS:-5000}" \
  "${OPS_GATEWAY_DAILY_TOKENS:-20000000}"

cat > .secrets/runtime.env <<EOF
# Generated by scripts/bootstrap-keys.sh. Do not commit.
GOGATE_API_KEY=${lmlog_key}
GOGATE_PLAYGROUND_API_KEY=${ops_key}
EOF
chmod 600 .secrets/runtime.env

echo "==> gateway keys are ready in .secrets/runtime.env"
echo "    lmlog           -> tenant lmlog"
echo "    ops-console     -> tenant ops-console"
